import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { readFileSync } from 'fs';
import { doc, setDoc, addDoc, updateDoc, collection, Timestamp, FieldPath, arrayUnion } from 'firebase/firestore';
const env = await initializeTestEnvironment({ projectId: 'demo-am', firestore: { rules: readFileSync('firestore.rules','utf8'), host:'127.0.0.1', port:8080 }});
await env.clearFirestore();
const db = u => env.authenticatedContext(u).firestore();
let ok=0, ng=0; const t = async (name, pr, expectOk) => { try { await (expectOk?assertSucceeds:assertFails)(pr); ok++; console.log('OK ', name);} catch(e){ ng++; console.log('NG ', name, e.message.slice(0,160));} };
await env.withSecurityRulesDisabled(async c => { const f=c.firestore();
  for (const [u,n] of [['A','みけ'],['B','ぽち'],['C','たま']]) await setDoc(doc(f,'users',u), {name:n});
  await setDoc(doc(f,'events/ev1'), {organizerUid:'A', title:'t'});
  await setDoc(doc(f,'events/ev1/participants/B'), {uid:'B'});
  await setDoc(doc(f,'events/ev1/participants/C'), {uid:'C'});
  await setDoc(doc(f,'events/ev1/messages/m1'), {text:'x', senderUid:'C', senderName:'たま', reactions:{}});
  await setDoc(doc(f,'blocks/A/blocked/B'), {createdAt: Timestamp.now()});
});
const msgs = u => collection(db(u),'events/ev1/messages');
await t('主催者にブロックされたBは、チャットに送れない', addDoc(msgs('B'), {text:'やあ', senderUid:'B', senderName:'ぽち'}), false);
await t('Bは、リアクションもつけられない', updateDoc(doc(db('B'),'events/ev1/messages/m1'), new FieldPath('reactions','paw'), arrayUnion('B')), false);
await t('Cは、ふつうに送れる', addDoc(msgs('C'), {text:'やあ', senderUid:'C', senderName:'たま'}), true);
await t('主催者Aも、ふつうに送れる', addDoc(msgs('A'), {text:'やあ', senderUid:'A', senderName:'みけ'}), true);
await t('Cは、リアクションをつけられる', updateDoc(doc(db('C'),'events/ev1/messages/m1'), new FieldPath('reactions','paw'), arrayUnion('C')), true);
console.log(`合計 OK ${ok} / NG ${ng}`);
await env.cleanup(); process.exit(ng?1:0);
