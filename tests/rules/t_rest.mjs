await t('お知らせ：参加しました（本物）', addDoc(msgs('B'), {text:'ぽちさんが参加しました🐾', senderUid:'system', senderName:'システム', senderImageUrl:'', isSystem:true, createdAt: serverTimestamp()}), true);
