import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { readFileSync } from 'fs';
import { doc, setDoc, updateDoc, deleteDoc, getDoc, serverTimestamp, Timestamp } from 'firebase/firestore';
const env = await initializeTestEnvironment({ projectId: 'demo-am', firestore: { rules: readFileSync('firestore.rules','utf8'), host:'127.0.0.1', port:8080 }});
await env.clearFirestore();
const db = u => env.authenticatedContext(u).firestore();
const anon = env.unauthenticatedContext().firestore();
let ok=0, ng=0; const t = async (name, pr, expectOk) => { try { await (expectOk?assertSucceeds:assertFails)(pr); ok++; console.log('OK ', name);} catch(e){ ng++; console.log('NG ', name, e.message.slice(0,160));} };
await env.withSecurityRulesDisabled(async c => { const f=c.firestore();
  await setDoc(doc(f,'admins/Z'), {x:1});
  await setDoc(doc(f,'park/2026-11-20/visitors/B'), {petName:'ぽち', ribbon:'ok', updatedAt: Timestamp.now()});
  await setDoc(doc(f,'park/2026-11-20/visitors/L'), {petName:'しずか', ribbon:'look', updatedAt: Timestamp.now()});
  await setDoc(doc(f,'blocks/B/blocked/X'), {createdAt: Timestamp.now()});
});
const tag = (extra={}) => ({petName:'みけ', ribbon:'ok', animal:'猫', emoji:'🐱', updatedAt: serverTimestamp(), ...extra});
const p = (u, owner=u, day='2026-11-20') => doc(db(u), `park/${day}/visitors/${owner}`);
await t('自分の名札を作れる', setDoc(p('A'), tag()), true);
await t('写真つきの名札を作れる', setDoc(p('C'), tag({petImage:'https://res.cloudinary.com/dx2xqewxb/image/upload/v1/a.jpg'})), true);
await t('ほかの人の名札は作れない', setDoc(p('A','D'), tag()), false);
await t('ほかのサイトの写真はだめ', setDoc(p('D'), tag({petImage:'https://evil.example.com/a.jpg'})), false);
await t('決まっていないリボンはだめ', setDoc(p('D'), tag({ribbon:'kiss'})), false);
await t('名前が空はだめ', setDoc(p('D'), tag({petName:''})), false);
await t('名前21文字はだめ', setDoc(p('D'), tag({petName:'あ'.repeat(21)})), false);
await t('ほかの項目（飼い主の名前など）はつけられない', setDoc(p('D'), tag({ownerName:'たろう'})), false);
await t('時刻を偽れない', setDoc(p('D'), tag({updatedAt: Timestamp.fromDate(new Date(2020,1,1))})), false);
await t('日付の形でない場所には作れない', setDoc(p('D','D','himitsu'), tag()), false);
await t('自分の名札のリボンを変えられる', setDoc(p('A'), tag({ribbon:'slow'})), true);
await t('ほかの人の名札は書きかえられない', updateDoc(p('A','B'), {ribbon:'look', updatedAt: serverTimestamp()}), false);
await t('ログインした人は読める', getDoc(p('A','B')), true);
await t('公園の中で歩ける（位置を書ける）', setDoc(p('A'), {x:0.4, y:0.7, updatedAt: serverTimestamp()}, {merge:true}), true);
await t('公園の外には出られない', setDoc(p('A'), {x:1.5, updatedAt: serverTimestamp()}, {merge:true}), false);
await t('決まったことばのふきだしを出せる', setDoc(p('A'), {say:'いい天気だね', sayAt: serverTimestamp(), updatedAt: serverTimestamp()}, {merge:true}), true);
await t('歩いても前のふきだしの時刻はそのまま', setDoc(p('A'), {x:0.5, updatedAt: serverTimestamp()}, {merge:true}), true);
await t('決まっていないことばは出せない', setDoc(p('A'), {say:'LINE教えて', sayAt: serverTimestamp(), updatedAt: serverTimestamp()}, {merge:true}), false);
await t('ふきだしの時刻を偽れない', setDoc(p('A'), {say:'かわいいね', sayAt: Timestamp.fromDate(new Date(2030,1,1)), updatedAt: serverTimestamp()}, {merge:true}), false);
await t('ログインしていない人は読めない', getDoc(doc(anon,'park/2026-11-20/visitors/B')), false);
await t('ほかの人の名札は消せない', deleteDoc(p('A','B')), false);
await t('運営は消せる', deleteDoc(p('Z','B')), true);
await t('自分の名札は消せる', deleteDoc(p('A')), true);
// 上で運営が B の名札を消したので、作りなおす
await env.withSecurityRulesDisabled(async c => { await setDoc(doc(c.firestore(),'park/2026-11-20/visitors/B'), {petName:'ぽち', ribbon:'ok', updatedAt: Timestamp.now()}); });
const hi = (from, to, extra={}) => setDoc(doc(db(from), `park/2026-11-20/visitors/${to}/hellos/${from}`), {phrase:'こんにちは🐾', fromPet:'みけ', createdAt: serverTimestamp(), ...extra});
await t('あいさつを送れる', hi('A','B'), true);
await t('決まっていないことばは送れない', hi('C','B',{phrase:'LINE教えて'}), false);
await t('ほかの人になりすまして送れない', setDoc(doc(db('C'), 'park/2026-11-20/visitors/B/hellos/A'), {phrase:'こんにちは🐾', fromPet:'みけ', createdAt: serverTimestamp()}), false);
await t('自分には送れない', hi('B','B'), false);
await t('ブロックされていたら送れない', hi('X','B'), false);
await t('「見るだけ」の子には送れない', hi('A','L'), false);
await t('ほかの項目はつけられない', hi('C','B',{phone:'090'}), false);
await t('送られた人は読める', getDoc(doc(db('B'), 'park/2026-11-20/visitors/B/hellos/A')), true);
await t('関係ない人は読めない', getDoc(doc(db('C'), 'park/2026-11-20/visitors/B/hellos/A')), false);
console.log(`公園の名札: OK ${ok} / NG ${ng}`);
await env.cleanup(); process.exit(ng?1:0);
