import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { readFileSync } from 'fs';
import { doc, setDoc, updateDoc, serverTimestamp } from 'firebase/firestore';
const env = await initializeTestEnvironment({ projectId: 'demo-am', firestore: { rules: readFileSync('firestore.rules','utf8'), host:'127.0.0.1', port:8080 }});
await env.clearFirestore();
const db = u => env.authenticatedContext(u).firestore();
const p = 'notifications/B/items/groupChat_ev1';
const base = u => ({ type:'groupChat', emoji:'👥', title:'グループチャットにメッセージが届きました！', desc:'x さんがメッセージを送りました', fromUid:u, eventId:'ev1', read:false, createdAt: serverTimestamp() });
let ok=0, ng=0; const t = async (name, pr, expectOk) => { try { await (expectOk?assertSucceeds:assertFails)(pr); ok++; console.log('OK ', name);} catch(e){ ng++; console.log('NG ', name, e.message);} };
await t('Aが通知を作る', setDoc(doc(db('A'), p), base('A')), true);
await t('Cが上書き（アプリと同じ）', setDoc(doc(db('C'), p), base('C')), true);
await t('Cが運営の通知に書きかえ', setDoc(doc(db('C'), p), {...base('C'), type:'admin', title:'AniMatch運営から'}), false);
await t('Cがお知らせに書きかえ(update)', updateDoc(doc(db('C'), p), {type:'announcement'}), false);
await t('CがAになりすまし', setDoc(doc(db('C'), p), base('A')), false);
await t('CがsenderUidにAを入れる', setDoc(doc(db('C'), p), {...base('C'), senderUid:'A'}), false);
await t('Cが101字のタイトル', setDoc(doc(db('C'), p), {...base('C'), title:'あ'.repeat(101)}), false);
await t('Cが301字の説明', setDoc(doc(db('C'), p), {...base('C'), desc:'あ'.repeat(301)}), false);
await t('Cが別のイベントIDに', setDoc(doc(db('C'), p), {...base('C'), eventId:'ev2'}), false);
await t('BがSを既読にする', updateDoc(doc(db('B'), p), {read:true}), true);
await env.withSecurityRulesDisabled(async c => setDoc(doc(c.firestore(), 'notifications/B/items/like1'), {type:'like', fromUid:'A', title:'t'}));
await t('Cがほかの通知を書きかえ', setDoc(doc(db('C'), 'notifications/B/items/like1'), {type:'like', fromUid:'C'}), false);
await t('Cが運営の通知を新しく作る', setDoc(doc(db('C'), 'notifications/B/items/x1'), {type:'admin', fromUid:'C', title:'t'}), false);
console.log(`合計 OK ${ok} / NG ${ng}`);
await env.cleanup(); process.exit(ng?1:0);
